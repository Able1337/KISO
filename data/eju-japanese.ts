import { tr, type EjuPack, type EjuQuestion } from '../lib/eju-types.ts';

type Item = [
  prompt: string,
  options: string[],
  correct: number,
  ru: string,
  en: string,
  ja: string,
];
const reading: EjuQuestion[] = [];
function passage(group: string, topic: string, text: string, items: Item[]) {
  for (const [prompt, options, correct, ru, en, ja] of items)
    reading.push({
      id: `jp-r${String(reading.length + 1).padStart(2, '0')}`,
      section: 'reading',
      topic,
      group,
      passage: text,
      prompt,
      kind: 'choice',
      options,
      answers: [String(correct)],
      explanation: tr(ru, en, ja),
    });
}
