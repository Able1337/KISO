import { tr, type EjuPack, type EjuQuestion } from '../lib/eju-types.ts';

// Independently authored Kiso problems. No JASSO passages, figures or answer keys are copied.
function q(
  id: string,
  topic: string,
  group: string,
  prompt: string,
  values: string[],
  calculation: string,
  hint: [string, string, string],
): EjuQuestion {
  return {
    id,
    topic,
    group,
    section: 'math',
    kind: 'numeric',
    prompt,
    answers: values.join('').split(''),
    labels: values.flatMap((value, i) =>
      value
        .split('')
        .map(
          (_, j) =>
            `${String.fromCharCode(65 + i)}${value.length > 1 ? j + 1 : ''}`,
        ),
    ),
    explanation: tr(
      `${calculation}\n${hint[0]}`,
      `${calculation}\n${hint[1]}`,
      `${calculation}\n${hint[2]}`,
    ),
  };
}
