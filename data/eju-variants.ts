export function variantPack(course: EjuCourse, variant: number): EjuPack {
  if (!Number.isInteger(variant) || variant < 2 || variant > 10)
    throw new Error('Variant must be 2–10');
  if (course === 'japanese') return japaneseVariant(variant);
  const base = mathPack(course),
    rows = mathRows(course, variant);
  const questions = rows.map(([prompt, raw, solution], i): EjuQuestion => {
    const values = raw.map(String);
    return {
      ...base.questions[i],
      id: `${base.questions[i].id}-v${variant}`,
      prompt,
      answers: values.join('').split(''),
      labels: values.flatMap((x, j) =>
        x
          .split('')
          .map(
            (_, k) =>
              String.fromCharCode(65 + j) + (x.length > 1 ? String(k + 1) : ''),
          ),
      ),
      explanation: tr(
        `Решение по шагам:\n${solution}`,
        `Step-by-step solution:\n${solution}`,
        `解法：\n${solution}`,
      ),
    };
  });
  return {
    ...base,
    id: `eju-${course}-kiso-${String(variant).padStart(2, '0')}`,
    title: tr(
      `Авторский вариант Kiso · ${variant}`,
      `Kiso original paper · ${variant}`,
      `Kiso独自問題・${variant}`,
    ),
    questions,
  };
}
