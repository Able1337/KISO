export const gcd = (a: number, b: number): number =>
  b ? gcd(b, a % b) : Math.abs(a);
const fraction = (a: number, b: number) => {
  const d = gcd(a, b);
  return [a / d, b / d];
};
type Row = [string, (number | string)[], string];
